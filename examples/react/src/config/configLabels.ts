/* ══════════════════ LIBELLÉS FRANÇAIS DE `MapConfig` ══════════════════
   Les noms de clés sont anglais (c'est l'API), le panneau est français : sans cette
   table, l'onglet Config afficherait « shape hit tolerance » à côté de « sévérité » et
   « poser une alerte ». Un panneau à moitié traduit se lit plus mal qu'un panneau
   entièrement anglais.

   Règles tenues ici :
   - court — un libellé qui déborde de la colonne ne se lit pas ;
   - PARLANT — ce que le réglage FAIT, pas la traduction mot à mot de sa clé
     (`backoffAuthMs` → « attente après refus d’identité », pas « backoff auth ») ;
   - l'unité entre parenthèses, jamais dans le mot ;
   - le contexte vient du dossier : dans « Cache », `ttlMs` est « durée de vie », il n'a
     pas à répéter « du cache ».

   Une clé sans entrée retombe sur `autoLabel` (dérivé du nom, donc anglais) :
   `configLabels.test.ts` échoue tant que c'est le cas. */

